//! Throughput benchmarks that separate each layer's cost: raw TCP, TLS,
//! hashing, the full protocol, and optionally the disk.
//!
//! Local runs put sender and receiver in one process over loopback, so CPU
//! figures cover both sides together. Remote runs (`send_generated` against a
//! receiver using `receive_into(.., Discard)`) measure a real network path
//! without either disk.

use std::future::Future;
use std::io::{self, Read, Seek, SeekFrom, Write};
use std::path::Path;
use std::time::{Duration, Instant};

use cpu_time::ProcessTime;
use tokio::io::{AsyncRead, AsyncReadExt, AsyncWrite, AsyncWriteExt};
use tokio::net::{TcpListener, TcpStream};

use crate::protocol::Offer;
use crate::transfer::{
    BUF_SIZE, CHUNK_SIZE, Sink, TransferStats, receive_file, receive_into, send_file, send_from,
};
use crate::{Identity, Result, Tls, TrustedPeers};

/// Name used for generated benchmark transfers.
pub const BENCH_FILE_NAME: &str = "nudge-bench.bin";

/// Generated bytes to send without touching a disk. Cheap to produce (a
/// repeating 1 MiB block of pseudo-random bytes), so it doesn't skew results.
pub struct Pattern {
    size: u64,
    pos: u64,
    block: Vec<u8>,
}

impl Pattern {
    pub fn new(size: u64) -> Self {
        let mut state = 0x9E37_79B9_7F4A_7C15u64;
        let block = (0..BUF_SIZE)
            .map(|_| {
                // xorshift64
                state ^= state << 13;
                state ^= state >> 7;
                state ^= state << 17;
                state as u8
            })
            .collect();
        Self {
            size,
            pos: 0,
            block,
        }
    }
}

impl Read for Pattern {
    fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
        let start = (self.pos % self.block.len() as u64) as usize;
        let n = buf
            .len()
            .min((self.size - self.pos.min(self.size)) as usize)
            .min(self.block.len() - start);
        buf[..n].copy_from_slice(&self.block[start..start + n]);
        self.pos += n as u64;
        Ok(n)
    }
}

impl Seek for Pattern {
    fn seek(&mut self, pos: SeekFrom) -> io::Result<u64> {
        let target = match pos {
            SeekFrom::Start(p) => Some(p),
            SeekFrom::End(d) => self.size.checked_add_signed(d),
            SeekFrom::Current(d) => self.pos.checked_add_signed(d),
        };
        self.pos = target.ok_or_else(|| io::Error::other("seek before start"))?;
        Ok(self.pos)
    }
}

/// Accepts and drops everything written to it.
pub struct Discard;

impl Write for Discard {
    fn write(&mut self, buf: &[u8]) -> io::Result<usize> {
        Ok(buf.len())
    }

    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}

impl Sink for Discard {
    fn sync(&mut self) -> io::Result<()> {
        Ok(())
    }
}

/// One benchmark result.
#[derive(Debug, Clone)]
pub struct Measurement {
    pub label: &'static str,
    pub bytes: u64,
    pub wall: Duration,
    /// CPU time used by this whole process during the run.
    pub cpu: Duration,
}

impl Measurement {
    pub fn mb_per_sec(&self) -> f64 {
        self.bytes as f64 / 1e6 / self.wall.as_secs_f64().max(1e-9)
    }

    /// Average number of CPU cores kept busy during the run.
    pub fn cores(&self) -> f64 {
        self.cpu.as_secs_f64() / self.wall.as_secs_f64().max(1e-9)
    }

    /// CPU seconds per GB moved: what matters for a phone's battery.
    pub fn cpu_sec_per_gb(&self) -> f64 {
        self.cpu.as_secs_f64() / (self.bytes as f64 / 1e9).max(1e-9)
    }
}

async fn measure<F, Fut>(label: &'static str, bytes: u64, run: F) -> Result<Measurement>
where
    F: FnOnce() -> Fut,
    Fut: Future<Output = Result<()>>,
{
    let cpu = ProcessTime::try_now()?;
    let wall = Instant::now();
    run().await?;
    Ok(Measurement {
        label,
        bytes,
        wall: wall.elapsed(),
        cpu: cpu.try_elapsed()?,
    })
}

/// Run every local benchmark with `size` bytes each. With `disk_dir`, also
/// time a real file-to-file transfer inside that folder (files are removed).
pub async fn run_local(size: u64, disk_dir: Option<&Path>) -> Result<Vec<Measurement>> {
    let identity = Identity::generate()?;
    // A device always trusts itself, so one identity serves both ends.
    let tls = Tls::new(&identity, TrustedPeers::default())?;

    let mut results = vec![
        raw_tcp(size).await?,
        raw_tls(&tls, size).await?,
        hashing(size).await?,
        protocol_in_memory(&tls, size).await?,
    ];
    if let Some(dir) = disk_dir {
        results.push(protocol_on_disk(&tls, size, dir).await?);
    }
    Ok(results)
}

/// Median time to send a 1-byte file over a brand-new TLS connection:
/// the fixed cost every transfer pays before data flows.
pub async fn setup_latency(runs: usize) -> Result<Duration> {
    let identity = Identity::generate()?;
    let tls = Tls::new(&identity, TrustedPeers::default())?;
    let mut times = Vec::with_capacity(runs);
    for _ in 0..runs {
        let start = Instant::now();
        protocol_once(&tls, 1).await?;
        times.push(start.elapsed());
    }
    times.sort();
    Ok(times[times.len() / 2])
}

/// Send `size` generated bytes through the full protocol, for measuring a
/// real network path against a receiver running `receive_into(.., Discard)`.
pub async fn send_generated<S>(stream: &mut S, size: u64) -> Result<TransferStats>
where
    S: AsyncRead + AsyncWrite + Unpin,
{
    let offer = Offer {
        name: BENCH_FILE_NAME.into(),
        size,
        modified: 0,
        batch: crate::protocol::Batch::single(size),
    };
    send_from(stream, Pattern::new(size), offer).await
}

async fn loopback() -> Result<(TcpListener, std::net::SocketAddr)> {
    let listener = TcpListener::bind("127.0.0.1:0").await?;
    let addr = listener.local_addr()?;
    Ok((listener, addr))
}

async fn accept(listener: &TcpListener) -> Result<TcpStream> {
    let (tcp, _) = listener.accept().await?;
    tcp.set_nodelay(true)?;
    Ok(tcp)
}

async fn connect(addr: std::net::SocketAddr) -> Result<TcpStream> {
    let tcp = TcpStream::connect(addr).await?;
    tcp.set_nodelay(true)?;
    Ok(tcp)
}

/// Write `size` bytes as fast as possible, in `BUF_SIZE` writes.
async fn blast<W: AsyncWrite + Unpin>(w: &mut W, size: u64) -> Result<()> {
    let mut source = Pattern::new(size);
    let mut buf = vec![0u8; BUF_SIZE];
    loop {
        let n = source.read(&mut buf)?;
        if n == 0 {
            break;
        }
        w.write_all(&buf[..n]).await?;
    }
    w.flush().await?;
    Ok(())
}

/// Read exactly `size` bytes and throw them away.
async fn drain<R: AsyncRead + Unpin>(r: &mut R, size: u64) -> Result<()> {
    let mut buf = vec![0u8; BUF_SIZE];
    let mut got = 0u64;
    while got < size {
        let n = r.read(&mut buf).await?;
        if n == 0 {
            return Err(io::Error::from(io::ErrorKind::UnexpectedEof).into());
        }
        got += n as u64;
    }
    Ok(())
}

async fn raw_tcp(size: u64) -> Result<Measurement> {
    let (listener, addr) = loopback().await?;
    measure("TCP, raw bytes", size, || async move {
        let receiver =
            tokio::spawn(async move { drain(&mut accept(&listener).await?, size).await });
        blast(&mut connect(addr).await?, size).await?;
        receiver.await.map_err(io::Error::other)?
    })
    .await
}

async fn raw_tls(tls: &Tls, size: u64) -> Result<Measurement> {
    let (listener, addr) = loopback().await?;
    let server = tls.clone();
    measure("TLS 1.3, raw bytes", size, || async move {
        let receiver = tokio::spawn(async move {
            let (mut stream, _) = server.accept(accept(&listener).await?).await?;
            drain(&mut stream, size).await
        });
        let (mut stream, _) = tls.connect(connect(addr).await?).await?;
        blast(&mut stream, size).await?;
        receiver.await.map_err(io::Error::other)?
    })
    .await
}

async fn hashing(size: u64) -> Result<Measurement> {
    measure("BLAKE3 hashing alone (one side)", size, || async move {
        tokio::task::spawn_blocking(move || -> Result<()> {
            let mut source = Pattern::new(size);
            let mut buf = vec![0u8; BUF_SIZE];
            let mut hasher = blake3::Hasher::new();
            let mut in_chunk = 0u64;
            loop {
                let n = source.read(&mut buf)?;
                if n == 0 {
                    break;
                }
                hasher.update(&buf[..n]);
                in_chunk += n as u64;
                if in_chunk == CHUNK_SIZE {
                    std::hint::black_box(hasher.finalize());
                    hasher.reset();
                    in_chunk = 0;
                }
            }
            std::hint::black_box(hasher.finalize());
            Ok(())
        })
        .await
        .map_err(io::Error::other)?
    })
    .await
}

async fn protocol_once(tls: &Tls, size: u64) -> Result<()> {
    let (listener, addr) = loopback().await?;
    let server = tls.clone();
    let receiver = tokio::spawn(async move {
        let (mut stream, _) = server.accept(accept(&listener).await?).await?;
        receive_into(&mut stream, Discard).await.map(|_| ())
    });
    let (mut stream, _) = tls.connect(connect(addr).await?).await?;
    send_generated(&mut stream, size).await?;
    receiver.await.map_err(io::Error::other)?
}

async fn protocol_in_memory(tls: &Tls, size: u64) -> Result<Measurement> {
    measure("Nudge protocol over TLS, memory to memory", size, || {
        protocol_once(tls, size)
    })
    .await
}

async fn protocol_on_disk(tls: &Tls, size: u64, dir: &Path) -> Result<Measurement> {
    let work = dir.join("nudge-bench");
    let out = work.join("received");
    std::fs::create_dir_all(&out)?;
    let src = work.join(BENCH_FILE_NAME);
    // Prepare the source file before timing starts.
    std::io::copy(&mut Pattern::new(size), &mut std::fs::File::create(&src)?)?;

    let (listener, addr) = loopback().await?;
    let server = tls.clone();
    let out_dir = out.clone();
    let result = measure(
        "Nudge protocol over TLS, disk to disk",
        size,
        || async move {
            let receiver = tokio::spawn(async move {
                let (mut stream, peer) = server.accept(accept(&listener).await?).await?;
                receive_file(&mut stream, &out_dir, Some(peer))
                    .await
                    .map(|_| ())
            });
            let (mut stream, _) = tls.connect(connect(addr).await?).await?;
            send_file(&mut stream, &src).await?;
            receiver.await.map_err(io::Error::other)?
        },
    )
    .await;
    let _ = std::fs::remove_dir_all(&work);
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pattern_reads_exact_size_and_seeks() {
        let mut p = Pattern::new(3 * BUF_SIZE as u64 + 7);
        let mut all = Vec::new();
        p.read_to_end(&mut all).unwrap();
        assert_eq!(all.len(), 3 * BUF_SIZE + 7);
        assert_eq!(all[..BUF_SIZE], all[BUF_SIZE..2 * BUF_SIZE]);

        p.seek(SeekFrom::Start(BUF_SIZE as u64 + 5)).unwrap();
        let mut one = [0u8; 1];
        p.read_exact(&mut one).unwrap();
        assert_eq!(one[0], all[BUF_SIZE + 5]);
    }

    #[tokio::test(flavor = "multi_thread")]
    async fn every_local_benchmark_runs() {
        let dir = tempfile::tempdir().unwrap();
        let results = run_local(CHUNK_SIZE + 123, Some(dir.path())).await.unwrap();
        assert_eq!(results.len(), 5);
        for r in &results {
            assert!(r.wall > Duration::ZERO, "{}", r.label);
        }
        assert!(setup_latency(3).await.unwrap() > Duration::ZERO);
        // The disk benchmark cleans up after itself.
        assert_eq!(std::fs::read_dir(dir.path()).unwrap().count(), 0);
    }
}
